use crate::model::Project;

#[allow(clippy::too_many_arguments)]
fn p(
    name: &str,
    cat: &'static str,
    stack: &str,
    bytes: u64,
    files: u64,
    loc: u64,
    src: u64,
    nm: u64,
    target: u64,
    other: u64,
    commits: u64,
    days: Option<u64>,
    dirty: u64,
    langs: &[(&'static str, u64)],
) -> Project {
    Project {
        name: name.to_string(),
        cat,
        stack: stack.to_string(),
        bytes,
        files,
        loc,
        src,
        nm,
        target,
        other,
        langs: langs.iter().map(|(l, n)| (l.to_string(), *n)).collect(),
        git: days.is_some() || commits > 0,
        commits,
        days,
        dirty,
    }
}

